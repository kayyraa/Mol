class SpatialGrid {
    constructor(CellSize) {
        this.CellSize = CellSize;
        this.InvCellSize = 1 / CellSize;
        this.Cells = new Map();
        this.Offset = 512;
        this.Stride1 = 1024;
        this.Stride2 = 1048576;
    }
    Clear() { this.Cells.clear(); }
    Insert(Index, X, Y, Z) {
        const cx = (X * this.InvCellSize | 0) + this.Offset;
        const cy = (Y * this.InvCellSize | 0) + this.Offset;
        const cz = (Z * this.InvCellSize | 0) + this.Offset;
        const Key = cx * this.Stride2 + cy * this.Stride1 + cz;
        let Cell = this.Cells.get(Key);
        if (Cell === undefined) { Cell = []; this.Cells.set(Key, Cell); }
        Cell.push(Index);
    }
    ForEachNear(X, Y, Z, Radius, Callback) {
        const Inv = this.InvCellSize;
        const MinX = ((X - Radius) * Inv | 0) + this.Offset;
        const MaxX = ((X + Radius) * Inv | 0) + this.Offset;
        const MinY = ((Y - Radius) * Inv | 0) + this.Offset;
        const MaxY = ((Y + Radius) * Inv | 0) + this.Offset;
        const MinZ = ((Z - Radius) * Inv | 0) + this.Offset;
        const MaxZ = ((Z + Radius) * Inv | 0) + this.Offset;
        const S1 = this.Stride1, S2 = this.Stride2, Cells = this.Cells;
        for (let cx = MinX; cx <= MaxX; cx++) {
            const BX = cx * S2;
            for (let cy = MinY; cy <= MaxY; cy++) {
                const BXY = BX + cy * S1;
                for (let cz = MinZ; cz <= MaxZ; cz++) {
                    const Cell = Cells.get(BXY + cz);
                    if (Cell !== undefined) {
                        for (let i = 0, N = Cell.length; i < N; i++) Callback(Cell[i]);
                    }
                }
            }
        }
    }
}

