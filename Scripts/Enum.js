function BuildIcosphere(Subdivisions) {
    const T = (1 + Math.sqrt(5)) / 2;
    let Vertices = [
        [-1,T,0],[1,T,0],[-1,-T,0],[1,-T,0],
        [0,-1,T],[0,1,T],[0,-1,-T],[0,1,-T],
        [T,0,-1],[T,0,1],[-T,0,-1],[-T,0,1]
    ];
    let Faces = [
        [0,11,5],[0,5,1],[0,1,7],[0,7,10],[0,10,11],
        [1,5,9],[5,11,4],[11,10,2],[10,7,6],[7,1,8],
        [3,9,4],[3,4,2],[3,2,6],[3,6,8],[3,8,9],
        [4,9,5],[2,4,11],[6,2,10],[8,6,7],[9,8,1]
    ];
    const Normalize = (V) => {
        const L = Math.sqrt(V[0]*V[0] + V[1]*V[1] + V[2]*V[2]);
        return [V[0]/L, V[1]/L, V[2]/L];
    };
    Vertices = Vertices.map(Normalize);
    const Cache = new Map();
    const Mid = (IA, IB) => {
        const K = IA < IB ? `${IA}_${IB}` : `${IB}_${IA}`;
        if (Cache.has(K)) return Cache.get(K);
        const A = Vertices[IA], B = Vertices[IB];
        const M = Normalize([(A[0]+B[0])/2, (A[1]+B[1])/2, (A[2]+B[2])/2]);
        Vertices.push(M);
        const Idx = Vertices.length - 1;
        Cache.set(K, Idx);
        return Idx;
    };
    for (let It = 0; It < Subdivisions; It++) {
        const NewFaces = [];
        for (const F of Faces) {
            const [A, B, C] = F;
            const AB = Mid(A, B), BC = Mid(B, C), CA = Mid(C, A);
            NewFaces.push([A, AB, CA], [B, BC, AB], [C, CA, BC], [AB, BC, CA]);
        }
        Faces = NewFaces;
    }
    const P = [], N = [], I = [];
    for (const V of Vertices) { P.push(V[0], V[1], V[2]); N.push(V[0], V[1], V[2]); }
    for (const F of Faces) I.push(F[0], F[1], F[2]);
    return {
        Positions: new Float32Array(P),
        Normals: new Float32Array(N),
        Indices: new Uint16Array(I)
    };
}

